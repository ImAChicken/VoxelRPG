#!/usr/bin/env python3
"""Draw the glyphs the UI font was missing (' ? ( ) + ; = % & * $ @ [ ] etc. as 8x8
pixel art in the font's style) into every resource pack's ui/font.png.
Only empty cells are filled: run it again and nothing changes."""
import sys
from PIL import Image

G = {
"'": ["...#....", "...#....", "..#.....", "........", "........", "........", "........", "........"],
"?": ["..###...", ".#...#..", "....#...", "...#....", "........", "...#....", "........", "........"],
"(": ["....#...", "...#....", "...#....", "...#....", "...#....", "....#...", "........", "........"],
")": ["..#.....", "...#....", "...#....", "...#....", "...#....", "..#.....", "........", "........"],
"+": ["........", "...#....", "...#....", ".#####..", "...#....", "...#....", "........", "........"],
";": ["........", "...#....", "........", "........", "...#....", "...#....", "..#.....", "........"],
"=": ["........", "........", ".#####..", "........", ".#####..", "........", "........", "........"],
"%": [".##..#..", ".##.#...", "...#....", "..#.....", ".#..##..", "#...##..", "........", "........"],
"&": ["..##....", ".#..#...", "..##....", ".#..#.#.", ".#...#..", "..###.#.", "........", "........"],
"*": ["........", ".#.#.#..", "..###...", ".#####..", "..###...", ".#.#.#..", "........", "........"],
"$": ["...#....", "..####..", ".#.#....", "..###...", "...#.#..", ".####...", "...#....", "........"],
"@": ["..###...", ".#...#..", ".#.###..", ".#.#.#..", ".#.##...", "..#.....", "...##...", "........"],
"\"": ["..#.#...", "..#.#...", "........", "........", "........", "........", "........", "........"],
}

def main(paths):
    for p in paths:
        im = Image.open(p).convert("RGBA")
        n = 0
        for ch, rows in G.items():
            i = ord(ch) - 32
            x0, y0 = (i % 16) * 8, (i // 16) * 8
            if any(im.getpixel((x0 + a, y0 + b))[3] > 0 for a in range(8) for b in range(8)):
                continue
            for b, row in enumerate(rows):
                for a, c in enumerate(row):
                    if c == "#":
                        im.putpixel((x0 + a, y0 + b), (255, 255, 255, 255))
            n += 1
        im.save(p)
        print(p, n, "glyphs added")

if __name__ == "__main__":
    main(sys.argv[1:] or ["data/resourcepacks/default/ui/font.png", "data/resourcepacks/jrpg/ui/font.png",
                          "data/resourcepacks/darktest/ui/font.png"])
